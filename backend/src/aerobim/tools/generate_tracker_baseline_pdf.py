def main() -> None:
    font_candidates = [
        Path(r"C:\Windows\Fonts\arial.ttf"),
        Path(r"C:\Windows\Fonts\segoeui.ttf"),
        Path(r"C:\Windows\Fonts\tahoma.ttf"),
    ]
    fontfile = next((p for p in font_candidates if p.exists()), None)
    if fontfile is None:
        raise SystemExit("No Cyrillic TTF found")

    fontname = "baseline-ru"
    doc = pymupdf.open()
    for lines in _pages():
        page = doc.new_page(width=595, height=842)
        page.insert_font(fontname=fontname, fontfile=str(fontfile))
        y = 50.0
        for text, size in lines:
            if text:
                page.insert_text(
                    (40, y),
                    text,
                    fontname=fontname,
                    fontsize=size,
                    color=(0, 0, 0),
                )
            y += size + 3.5 if text else 7.0
            if y > 800:
                break

    OUT_PRIMARY.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT_PRIMARY, garbage=4, deflate=True)
    doc.save(OUT_ALIAS, garbage=4, deflate=True)
    doc.close()
    print(f"wrote {OUT_PRIMARY} and alias {OUT_ALIAS.name} bytes={OUT_PRIMARY.stat().st_size}")


if __name__ == "__main__":
    raise SystemExit(main())
